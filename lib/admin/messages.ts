export type AdminMessage = { type: 'success' | 'error'; text: string };

export function messageFromQuery(status?: string, error?: string): AdminMessage | null {
  if (error) {
    return { type: 'error', text: ERROR_MESSAGES[error] ?? 'تعذر إكمال العملية. حاول مرة أخرى.' };
  }
  if (status) {
    return { type: 'success', text: STATUS_MESSAGES[status] ?? 'تمت العملية بنجاح.' };
  }
  return null;
}
